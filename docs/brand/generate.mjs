/*
  Writes every still picture of Ele from the one drawing in
  src/EleFi.App/wwwroot/js/elefi-ele-shape.js, which the live mascot draws from too.

      node docs/brand/generate.mjs              writes the pictures below
      node docs/brand/generate.mjs preview.svg  also writes a sheet of every mood

  Writes:
    src/EleFi.App/Resources/AppIcon/appiconfg.svg                    the icon's foreground layer
    src/EleFi.App/Resources/Splash/splash.svg                        the launch screen
    src/EleFi.App/Platforms/Android/Resources/drawable/boot_ele.xml  the start-up window
    docs/brand/elefi-icon.svg                                        the standalone icon

  The launcher PNGs in docs/brand/android are copied from the build's own resizing of the
  icon (obj/.../resizetizer), so they follow from these after a build.
*/

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  CHEEK, EAR_INNER, EAR_OUTER, EYE, FOREHEAD, HEAD, PUPIL, SHINES, TUSK, lowerLid, lowerLidEdge, trunk, upperLid, upperLidEdge,
} from '../../src/EleFi.App/wwwroot/js/elefi-ele-shape.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const write = (path, text) => writeFileSync(join(root, path), text.replace(/\r\n/g, '\n'), 'utf8');

// At rest, with the trunk's tip curled up: cheerful, and the clearest elephant at 48dp.
const ICON_CURL = 0;

/** Ele as SVG elements in shape units, coloured for a dark ground. */
function svgEle({ curl = ICON_CURL, lidIn = 0, lidOut = 0, smile = 0, ids = 'ele' } = {}) {
  const t = trunk(curl, 0);
  const hide = `url(#${ids}-hide)`;
  const earInner = `url(#${ids}-ear)`;
  const ink = '#231A3D';
  const fold = '#8466EE';
  const side = (body) => `${body}\n    <g transform="scale(-1 1)">${body}</g>`;

  return `
    <!-- Ears behind the head, the left one the right one mirrored. -->
    ${side(`<path d="${EAR_OUTER}" fill="${hide}"/><path d="${EAR_INNER}" fill="${earInner}"/>`)}
    <!-- Tusks, then the trunk over their roots. -->
    ${side(`<path d="${TUSK}" fill="#FFFBF2" stroke="#C4B48C" stroke-width="0.9"/>`)}
    <path d="${HEAD}" fill="${hide}"/>
    <path d="${FOREHEAD}" fill="#FFFFFF" opacity="0.35"/>
    <path d="${t.outline}" fill="${hide}"/>
    ${t.wrinkles.map((w) => `<path d="${w}" fill="none" stroke="${fold}" stroke-width="1.1" stroke-linecap="round"/>`).join('\n    ')}

    ${side(`<ellipse cx="${CHEEK.x}" cy="${CHEEK.y}" rx="${CHEEK.rx}" ry="${CHEEK.ry}" fill="#FFFFFF" opacity="0.2"/>`)}
    <clipPath id="${ids}-eye"><ellipse cx="${EYE.x}" cy="${EYE.y}" rx="${EYE.rx}" ry="${EYE.ry}"/></clipPath>
    ${side([
      `<ellipse cx="${EYE.x}" cy="${EYE.y}" rx="${EYE.rx}" ry="${EYE.ry}" fill="#FFFFFF"/>`,
      `<g clip-path="url(#${ids}-eye)">`,
      `<circle cx="${EYE.x + PUPIL.dx}" cy="${EYE.y + PUPIL.dy}" r="${PUPIL.r}" fill="${ink}"/>`,
      ...SHINES.map((s) => `<circle cx="${EYE.x + PUPIL.dx + s.dx}" cy="${EYE.y + PUPIL.dy + s.dy}" r="${s.r}" fill="#FFFFFF"/>`),
      `<path d="${upperLid(lidIn, lidOut)}" fill="${hide}"/>`,
      `<path d="${upperLidEdge(lidIn, lidOut)}" fill="none" stroke="${ink}" stroke-width="1.4" stroke-linecap="round" opacity="${Math.min(0.7, 0.18 + Math.max(lidIn, lidOut) * 0.08)}"/>`,
      smile > 0 ? `<path d="${lowerLid(smile)}" fill="${hide}"/><path d="${lowerLidEdge(smile)}" fill="none" stroke="${ink}" stroke-width="1.4" stroke-linecap="round" opacity="0.7"/>` : '',
      '</g>',
      `<ellipse cx="${EYE.x}" cy="${EYE.y}" rx="${EYE.rx}" ry="${EYE.ry}" fill="none" stroke="${ink}" stroke-width="0.9" opacity="0.3"/>`,
    ].join(''))}`;
}

function gradients(ids = 'ele') {
  return `
  <defs>
    <!-- One gradient across the whole elephant, in shape units, so the trunk joins the head
         without a seam. -->
    <linearGradient id="${ids}-hide" gradientUnits="userSpaceOnUse" x1="0" y1="-37" x2="0" y2="58">
      <stop offset="0" stop-color="#C2ABFF"/>
      <stop offset="1" stop-color="#9E80F8"/>
    </linearGradient>
    <linearGradient id="${ids}-ear" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#8D6FF2"/>
      <stop offset="1" stop-color="#7353DC"/>
    </linearGradient>
  </defs>`;
}

// The drawing spans x -62..62 and y -38..48 in shape units, so its centre is y 5.
// On a 512 grid, scale 2.5 keeps it inside the adaptive icon's safe middle (about 87..425).
const PLACE = 'translate(256 244) scale(2.45)';

// The icon draws Ele larger: the build scales its foreground to 85% (ForegroundScale) and a
// launcher shows it at 48dp, where every pixel of elephant counts. The ear tips still fall
// inside the adaptive icon's safe circle.
const ICON_PLACE = 'translate(256 242) scale(2.85)';

const generated = (what) => `<!--
    ${what}

    GENERATED by docs/brand/generate.mjs from src/EleFi.App/wwwroot/js/elefi-ele-shape.js,
    the same drawing the live mascot uses. Do not edit by hand: change the shape and rerun.
-->`;

write('src/EleFi.App/Resources/AppIcon/appiconfg.svg', `<?xml version="1.0" encoding="UTF-8"?>
${generated(`Ele, the mascot, as the icon foreground. Android adaptive icons crop the outer third,
    so Ele sits inside the middle two thirds of the 512 grid.`)}
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512">${gradients()}
  <g transform="${ICON_PLACE}">${svgEle()}
  </g>
</svg>
`);

write('src/EleFi.App/Resources/Splash/splash.svg', `<?xml version="1.0" encoding="UTF-8"?>
${generated('The launch screen: Ele alone on the brand ground, which the csproj supplies as Color.')}
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512">${gradients()}
  <g transform="${PLACE}">${svgEle()}
  </g>
</svg>
`);

write('docs/brand/elefi-icon.svg', `<?xml version="1.0" encoding="UTF-8"?>
${generated(`Ele, complete: background and mascot in one file, for anything that wants a single
    image (a store listing, a README). Rasterise at any size, for example:
        magick -background none -density 600 elefi-icon.svg -resize 512x512 elefi-icon-512.png`)}
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512">${gradients()}
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#6E5A96"/>
      <stop offset="1" stop-color="#4A3E6B"/>
    </linearGradient>
  </defs>
  <rect width="512" height="512" rx="112" fill="url(#bg)"/>
  <g transform="${ICON_PLACE}">${svgEle()}
  </g>
</svg>
`);

// The start-up window. An Android vector cannot take an SVG gradient without extra syntax,
// so it uses the flat mascot colours the app's own tokens define.
{
  const t = trunk(ICON_CURL, 0);
  const pair = (body) => `${body}
            <group android:scaleX="-1">
${body}
            </group>`;
  const path = (d, attrs) => `                <path ${attrs} android:pathData="${d}" />`;
  const ears = pair([
    path(EAR_OUTER, 'android:fillColor="@color/ele_mascot_hide"'),
    path(EAR_INNER, 'android:fillColor="@color/ele_mascot_hide_dark"'),
  ].join('\n'));
  const tusks = pair(path(TUSK, 'android:fillColor="#FFFBF2" android:strokeColor="#C4B48C" android:strokeWidth="0.9"'));
  const oval = (x, y, rx, ry) => `M ${x - rx},${y} a ${rx},${ry} 0 1,0 ${rx * 2},0 a ${rx},${ry} 0 1,0 ${-rx * 2},0`;
  // The pupil sits wholly inside the white, so the still eye needs no clipping.
  const cheeks = pair(path(oval(CHEEK.x, CHEEK.y, CHEEK.rx, CHEEK.ry), 'android:fillColor="#FFFFFF" android:fillAlpha="0.2"'));
  const eyes = pair([
    path(oval(EYE.x, EYE.y, EYE.rx, EYE.ry), 'android:fillColor="#FFFFFF" android:strokeColor="@color/ele_mascot_ink" android:strokeWidth="0.9" android:strokeAlpha="0.3"'),
    path(oval(EYE.x + PUPIL.dx, EYE.y + PUPIL.dy, PUPIL.r, PUPIL.r), 'android:fillColor="@color/ele_mascot_ink"'),
    ...SHINES.map((s) => path(oval(EYE.x + PUPIL.dx + s.dx, EYE.y + PUPIL.dy + s.dy, s.r, s.r), 'android:fillColor="#FFFFFF"')),
  ].join('\n'));
  const folds = t.wrinkles
    .map((d) => path(d, 'android:strokeColor="@color/ele_mascot_hide_dark" android:strokeWidth="1.1" android:strokeLineCap="round"'))
    .join('\n');

  write('src/EleFi.App/Platforms/Android/Resources/drawable/boot_ele.xml', `<?xml version="1.0" encoding="utf-8"?>
<!-- Ele as on the loading screen. A vector, so Android can draw it
     before the WebView exists and animate it on the render thread while the app starts.

     288dp with Ele about 132dp wide in the middle: the size Android 12's splash screen gives an
     icon with no background. .boot-words in app.css places the greeting just under it. The
     inner group "ele" is what boot_float.xml moves.

     GENERATED by docs/brand/generate.mjs from src/EleFi.App/wwwroot/js/elefi-ele-shape.js.
     Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="288dp"
    android:height="288dp"
    android:viewportWidth="288"
    android:viewportHeight="288">
    <group android:translateX="144" android:translateY="139" android:scaleX="1.06" android:scaleY="1.06">
        <group android:name="ele" android:pivotX="0" android:pivotY="5">
${ears}
${tusks}
${path(HEAD, 'android:fillColor="@color/ele_mascot_hide"')}
${path(t.outline, 'android:fillColor="@color/ele_mascot_hide"')}
${folds}
${cheeks}
${eyes}
        </group>
    </group>
</vector>
`);
}

// A sheet of every mood, for checking a change by eye before building.
const previewPath = process.argv[2];
if (previewPath) {
  const moods = [
    ['Pleased', { curl: 1, smile: 1 }],
    ['At rest', { curl: 0 }],
    ['Thinking', { curl: 0.1, lidIn: 3, lidOut: 3 }],
    ['Cross', { curl: -0.35, lidIn: 9.5, lidOut: 2.5 }],
    ['Sad', { curl: -0.7, lidIn: 2.5, lidOut: 9.5 }],
  ];
  const cells = moods.map(([name, pose], i) => `
  <g transform="translate(${130 + i * 250} 150) scale(1.7)">${svgEle({ ...pose, ids: `p${i}` })}
  </g>
  <text x="${130 + i * 250}" y="290" font-family="sans-serif" font-size="22" fill="#fff" text-anchor="middle">${name}</text>`).join('');
  writeFileSync(previewPath, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1250 640" width="1250" height="640">${[0, 1, 2, 3, 4].map((i) => gradients(`p${i}`)).join('')}${gradients('p')}
  <rect width="1250" height="640" fill="#1B1F2A"/>${cells}
  <rect x="380" y="330" width="290" height="290" rx="64" fill="#5A4A82"/>
  <g transform="translate(525 467) scale(1.42)">${svgEle({ ids: 'p' })}</g>
  <g transform="translate(860 475)"><rect x="-45" y="-45" width="90" height="90" rx="20" fill="#5A4A82"/><g transform="scale(0.44)">${svgEle({ ids: 'p' })}</g></g>
</svg>
`, 'utf8');
}
